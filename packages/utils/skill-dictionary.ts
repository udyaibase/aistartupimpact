/**
 * Skills dictionary: the base list (in code), shared by the web app and admin. Admin can add aliases, skills, implies
 * rules and ambiguity marks on top (database); those override this list on the server.
 *
 * - name: the canonical spelling shown to people. Its key is baseKey(name); keys of skills that existed before this
 *   file (nodejs, postgresql, machinelearning, llms, ...) must not change, or stored matches stop lining up.
 * - aliases: every other way people write it. Written out explicitly: a dictionary is safer than clever rules.
 * - loose: aliases that are everyday words, used only for whole skill tags, never when reading resume text.
 * - ambiguous: also an everyday word ("Go", "React", "Spark"): only counts when written as the tool's name.
 * - implies: knowing this shows related (not full) experience of those skills, e.g. Next.js implies React.
 */

export type SkillCategory =
  | 'language' | 'frontend' | 'backend' | 'mobile' | 'data' | 'database' | 'ml' | 'ai' | 'cloud' | 'devops'
  | 'testing' | 'security' | 'design' | 'product' | 'business' | 'soft' | 'tools';

export interface SkillEntry {
  name: string; category: SkillCategory; aliases?: string[];
  /** Everyday words ("rest", "growth", "CV"): count only as a whole skill tag (a job's skills, a ticked skill), never inside resume sentences. */
  loose?: string[];
  ambiguous?: boolean; implies?: string[];
}

/** The normalised key every comparison uses: lowercase, ".js" kept as "js", everything but letters, digits, + and # removed. */
export function baseKey(s: string): string {
  return s.normalize('NFKC').toLowerCase().replace(/\.js\b/g, 'js').replace(/[^a-z0-9+#]/g, '');
}

